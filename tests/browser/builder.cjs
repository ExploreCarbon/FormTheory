const css = ['wp-includes/css/buttons.css','wp-admin/css/common.css','wp-admin/css/forms.css'].map(f => fs.readFileSync(path.join(site,f),'utf8')).join('\n') + fs.readFileSync(path.join(root,'assets/admin.css'),'utf8');
const html = `<html><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}body{margin:0;background:#f0f0f1;font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;color:#1d2327;font-size:13px}.wrap{margin:24px}button,input,select,textarea{font-family:inherit}</style></head><body><div class="wrap ft-builder-page"><h1>Edit Form</h1><p>Embed: <code>[formtheory id="1"]</code></p><form id="ft-builder-form"><p><label for="ft-title"><strong>Form title</strong></label><br><input id="ft-title" required value="Contact" class="regular-text"></p><textarea id="ft-config" hidden>${JSON.stringify(config)}</textarea><div id="ft-builder"></div><p class="submit"><button type="submit" class="button button-primary">Save Form</button></p></form></div></body></html>`;
