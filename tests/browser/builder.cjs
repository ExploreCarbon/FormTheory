const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const site = process.env.FORMTHEORY_WP_ROOT || path.resolve(root, '../..');
const artifacts = path.join(root, '.qa');
const config = { fields: [{id:'f1',type:'text',label:'Full name',required:true},{id:'f2',type:'email',label:'Email address',required:true}], submit_label:'Send message', confirmation:'Thank you.', notifications:[], webhooks:[] };
