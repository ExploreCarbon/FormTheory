 await page.locator('#ftb-panel-webhooks details').evaluate(n=>n.open=false);
 await page.getByRole('button',{name:'Fields',exact:true}).click();
 await page.getByRole('button',{name:'Save Form',exact:true}).click();
 assert.equal(await page.locator('#ftb-panel-settings').isVisible(),true,'reveal invalid hidden setting');
 await page.getByLabel('Redirect URL (merge tags allowed in path/query)',{exact:true}).fill('https://example.com/thanks');
 await page.getByRole('button',{name:'Save Form',exact:true}).click();
 assert.equal(await page.locator('#ftb-panel-webhooks').isVisible(),true);
 assert.equal(await page.locator('#ftb-panel-webhooks details').getAttribute('open'),'');
 await page.getByLabel('Endpoint URL (https only)',{exact:true}).fill('https://example.com/hook');
 await page.locator('#ft-builder-form').evaluate(n => n.addEventListener('submit',e=>e.preventDefault()));
 await page.getByRole('button',{name:'Save Form',exact:true}).click();
 const saved=JSON.parse(await page.locator('#ft-config').inputValue());
 assert.equal(saved.fields.length,4); assert.equal(saved.submit_label,'Send inquiry'); assert.equal(saved.confirmation_url,'https://example.com/thanks');
 assert.equal(await page.evaluate(() => {const e=new Event('beforeunload',{cancelable:true});window.dispatchEvent(e);return e.defaultPrevented;}),false);
 assert.deepEqual(errors,[]);
 const settings=fs.readFileSync(path.join(artifacts,'settings.html'),'utf8');
