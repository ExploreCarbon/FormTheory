 await page.getByLabel('Submit button text',{exact:true}).fill('Send inquiry');
 assert.equal(await page.locator('.ftb-save-state').textContent(),'Unsaved changes');
 assert.equal(await page.evaluate(() => {const e=new Event('beforeunload',{cancelable:true});window.dispatchEvent(e);return e.defaultPrevented;}),true);
 await page.getByRole('button',{name:'Fields',exact:true}).click();
 await page.getByRole('button',{name:'Paragraph',exact:true}).click();
 assert.equal(await page.locator('.ftb-list > details').count(),3);
 assert.equal(await page.locator('.ftb-list > details').last().getAttribute('open'),'');
 await page.getByLabel('Label',{exact:true}).last().fill('How can we help?');
 await page.getByRole('button',{name:'Duplicate Paragraph: Paragraph'}).count();
 await page.locator('.ftb-list > details').last().getByRole('button',{name:/Duplicate/}).click();
 assert.equal(await page.locator('.ftb-list > details').count(),4);
 await page.getByRole('button',{name:'Collapse all',exact:true}).click();
 assert.equal(await page.locator('.ftb-list > details[open]').count(),0);
 await page.getByRole('button',{name:'Expand all',exact:true}).click();
 assert.equal(await page.locator('.ftb-list > details[open]').count(),4);
 await page.setViewportSize({width:390,height:844});
 await page.locator('.ftb-field-picker').evaluate(n=>n.open=false);
 await page.getByRole('button',{name:'Collapse all',exact:true}).click();
 await page.screenshot({path:path.join(artifacts,'builder-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,'mobile overflow');
 await page.getByRole('button',{name:'Form settings',exact:true}).click();
 await page.getByLabel('After submit',{exact:true}).selectOption('redirect');
 await page.getByLabel('Redirect URL (merge tags allowed in path/query)',{exact:true}).fill('invalid');
 await page.getByRole('button',{name:'Webhooks',exact:true}).click();
 await page.getByRole('button',{name:'Add webhook',exact:true}).click();
